// Compiles the system-prompt sections under packages/runtime/resources/prompts
// into one generated TypeScript module, the way gen-bundled-skill-catalog.mjs
// compiles SKILL.md files. Prompt text lives in Markdown so a wording change is
// a diff of prose, not of a string literal; the generated module is what the
// Runtime imports, so nothing is read from disk at run time.
//
// Each section is one file: numeric prefix for review order, YAML front-matter
// with `id`, `layer` (`static` = provider-stable prefix shared by every
// session; `session` = varies per session but not per turn), `order`, and
// an optional `condition` the assembler evaluates by name.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcesDir = join(repositoryRoot, 'packages', 'runtime', 'resources', 'prompts');
const outFile = join(
  repositoryRoot,
  'packages',
  'runtime',
  'src',
  'system-prompt',
  'prompt-catalog.generated.ts',
);
const FILE_RE = /^\d{2}-[a-z0-9-]+\.md$/u;
const ID_RE = /^[a-z][a-z0-9-]{0,60}$/u;
const LAYERS = new Set(['static', 'session']);

function parseFrontMatter(file, text) {
  const match = /^---\n([\s\S]*?)\n---\n?/u.exec(text);
  if (!match) throw new Error(`prompt section ${file} is missing YAML front-matter`);
  const meta = {};
  for (const line of match[1].split('\n')) {
    if (!line.trim()) continue;
    const separator = line.indexOf(':');
    if (separator === -1) throw new Error(`prompt section ${file}: bad front-matter line ${line}`);
    meta[line.slice(0, separator).trim()] = line.slice(separator + 1).trim();
  }
  return { meta, body: text.slice(match[0].length).replace(/\s+$/u, '') };
}

export function readPromptSections(dir = sourcesDir) {
  const files = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && FILE_RE.test(entry.name))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
  const seen = new Set();
  return files.map((file) => {
    const text = readFileSync(join(dir, file), 'utf8');
    const { meta, body } = parseFrontMatter(file, text);
    if (!ID_RE.test(meta.id ?? '')) throw new Error(`prompt section ${file}: invalid id`);
    if (seen.has(meta.id)) throw new Error(`prompt section ${file}: duplicate id ${meta.id}`);
    seen.add(meta.id);
    if (!LAYERS.has(meta.layer)) throw new Error(`prompt section ${file}: invalid layer`);
    const order = Number(meta.order);
    if (!Number.isInteger(order)) throw new Error(`prompt section ${file}: invalid order`);
    if (!body) throw new Error(`prompt section ${file}: empty body`);
    return {
      id: meta.id,
      layer: meta.layer,
      order,
      ...(meta.condition ? { condition: meta.condition } : {}),
      body,
      contentSha256: `sha256:${createHash('sha256').update(body).digest('hex')}`,
    };
  });
}

export function renderGeneratedModule(sections) {
  const entries = sections
    .map(
      (section) =>
        `  { id: ${JSON.stringify(section.id)}, layer: ${JSON.stringify(section.layer)}, order: ${section.order}, condition: ${JSON.stringify(section.condition ?? null)}, body: ${JSON.stringify(section.body)}, contentSha256: ${JSON.stringify(section.contentSha256)} },`,
    )
    .join('\n');
  return `// @generated by scripts/gen-prompt-catalog.mjs — do not edit by hand.
// Source of truth: packages/runtime/resources/prompts/<order>-<id>.md
// Regenerate: npm run generate:prompts

export type PromptSectionLayer = 'static' | 'session';

export interface PromptSection {
  id: string;
  layer: PromptSectionLayer;
  order: number;
  /** Named condition the assembler evaluates; null means always included. */
  condition: string | null;
  body: string;
  contentSha256: string;
}

// biome-ignore format: generated catalog keeps one reviewable section per line.
export const PROMPT_CATALOG: ReadonlyArray<PromptSection> = [
${entries}
];
`;
}

export function expectedPromptCatalog() {
  return renderGeneratedModule(readPromptSections());
}

function main() {
  const expected = expectedPromptCatalog();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(outFile, 'utf8');
    } catch {
      current = '';
    }
    if (current !== expected) {
      throw new Error('Prompt catalog is stale; run npm run generate:prompts');
    }
    console.log('[gen] prompt catalog is current');
    return;
  }
  writeFileSync(outFile, expected, 'utf8');
  console.log(`[gen] wrote ${readPromptSections().length} prompt sections -> ${outFile}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
