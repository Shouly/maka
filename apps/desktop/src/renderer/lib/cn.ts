// The class-name joiner every ported component imports (the reference design
// system keeps it in `lib/utils/common-utils.ts`; the rest of that module is
// relx-server file/URL helpers Maka does not need). `clsx` flattens the
// conditional forms, `twMerge` resolves Tailwind conflicts last-wins so a
// caller's `className` can override a component's defaults.

import { type ClassValue, clsx } from 'clsx';
import { twMerge } from 'tailwind-merge';

export function cn(...inputs: ClassValue[]): string {
  return twMerge(clsx(inputs));
}
